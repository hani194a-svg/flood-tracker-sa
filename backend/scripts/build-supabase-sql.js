// Concatenates every migration (+ optional seed) into db/supabase_setup.sql,
// a single file you can paste into Supabase → SQL Editor and run once.
// It also records the migrations in schema_migrations, so `npm run migrate`
// later only applies NEW migrations.
//
// Usage: npm run build:supabase-sql            (regenerate after adding a migration)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../db');
const files = (await fs.readdir(path.join(root, 'migrations'))).filter((f) => f.endsWith('.sql')).sort();

const parts = [
  '-- ════════════════════════════════════════════════════════════════════',
  '-- GENERATED by backend/scripts/build-supabase-sql.js — do not edit by hand.',
  '-- Paste into Supabase → SQL Editor → Run. Safe to re-run.',
  '-- ════════════════════════════════════════════════════════════════════',
  '',
  'BEGIN;',
  '',
  `CREATE TABLE IF NOT EXISTS public.schema_migrations (
  name TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());`,
  '',
];

for (const f of files) {
  const sql = await fs.readFile(path.join(root, 'migrations', f), 'utf8');
  parts.push(`-- ┌─── ${f} ───`, sql.trim(), `INSERT INTO public.schema_migrations (name) VALUES ('${f}') ON CONFLICT DO NOTHING;`, '');
}

parts.push('COMMIT;', '');

const out = path.join(root, 'supabase_setup.sql');
await fs.writeFile(out, parts.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)} (${files.length} migrations)`);
